function compileToPython(graph) {
    let code = [];
    code.push("import torch");
    code.push("import torch.nn as nn");
    code.push("");
    code.push("# Generated by SketchNet");
    code.push("");
    code.push("class Model(nn.Module):");
    code.push("    def __init__(self):");
    code.push("        super().__init__()");

    const layers = graph.nodes.filter(
        (n) => n.nodeType === "layer" || n.nodeType === "neuron",
    );
    code.push("        self.layers = nn.Sequential(");
    layers.forEach((layer, i) => {
        code.push(`            nn.Linear(64, 64),`);
        code.push(`            nn.ReLU(),`);
    });
    code.push("        )");
    code.push("");
    code.push("    def forward(self, x):");
    code.push("        return self.layers(x)");
    code.push("");
    code.push("# Initialize and run");
    code.push("model = Model()");
    code.push("print(model)");

    return code.join("\n");
}

function downloadFile(filename, content) {
    const blob = new Blob([content], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
}
